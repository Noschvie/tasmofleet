STATES = ((":hover", ".is-hover"), (":active", ".is-active"), (":focus-visible", ".is-focus"))


def state_hooks(lines):
    """Give every :hover/:active/:focus-visible selector a class twin
    (.is-hover, .is-active, .is-focus), so previews and the app's styleguide
    page can show a state statically."""
    res = []
    for line in lines:
        stripped = line.rstrip()
        if stripped.endswith((",", "{")) and any(p in stripped for p, _ in STATES) and ";" not in stripped:
            end = "{" if stripped.endswith("{") else ","
            sel = stripped[:-1].rstrip()
            twin = sel
            for pseudo, cls in STATES:
                twin = twin.replace(pseudo, cls)
            pad = line[: len(line) - len(line.lstrip())]
            res.append(f"{sel},")
            res.append(f"{pad}{twin.strip()} {end}" if end == "{" else f"{pad}{twin.strip()},")
        else:
            res.append(line)
    return res


def main():
    ramps = subprocess.run(
        [sys.executable, "-I", os.path.join(HERE, "ramps.py")],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    ramps = ramps.replace("  --light-", "  --prim-light-").replace(
        "  --dark-", "  --prim-dark-"
    )
    src = open(os.path.join(HERE, "styles.src.css")).read()
    begin, end = "/* RAMPS-BEGIN */", "/* RAMPS-END */"
    a, b = src.index(begin), src.index(end)
    src = (
        src[:a]
        + "/* ramps: generated by tools/ramps.py */\n"
        + ramps.rstrip()
        + "\n  /* end of ramps */"
        + src[b + len(end) :]
    )
    out = []
    for line in src.split("\n"):
        if line.strip() == "/* DARK-TOKENS */":
            pad = line[: len(line) - len(line.lstrip())]
            out.extend(pad + t for t in DARK.split("\n"))
        else:
            out.append(line)
    css = "\n".join(state_hooks(out))
    css = css.replace(
        "edit tools/styles.src.css and run tools/build.py, never this file.",
        "edit tools/styles.src.css and run tools/build.py, never this file.",
    )
    with open(os.path.join(ROOT, "ds-bundle", "styles.css"), "w") as f:
        f.write(css)
    print("wrote ds-bundle/styles.css", len(css), "bytes")


if __name__ == "__main__":
    main()
